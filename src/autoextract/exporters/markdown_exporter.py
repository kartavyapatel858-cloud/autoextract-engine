"""Markdown Summary and Audit Report Exporter."""

from __future__ import annotations

from pathlib import Path
from typing import List, Optional

from autoextract.core.exceptions import ExportError
from autoextract.core.models import EngineStats, ExportConfig, ExtractedRecord
from autoextract.exporters.base import BaseExporter


class MarkdownExporter(BaseExporter):
    """Exports executive extraction summary reports formatted in GitHub Markdown."""

    def export(
        self,
        records: List[ExtractedRecord],
        stats: Optional[EngineStats] = None,
        config: Optional[ExportConfig] = None,
    ) -> Path:
        cfg = config or ExportConfig()
        output_dir = Path(cfg.output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        target_file = output_dir / f"{cfg.base_filename}_summary.md"

        try:
            lines = [
                "# 🚀 AutoExtract Engine - Execution Report",
                "",
                f"> Generated on `{stats.end_time if stats and stats.end_time else 'N/A'}`",
                "",
                "## 📊 Executive Metrics",
                "",
                "| Metric | Value |",
                "| :--- | :--- |",
                f"| **Total Targets** | `{stats.total_targets if stats else len(records)}` |",
                f"| **Successful Extractions** | `{stats.successful if stats else sum(1 for r in records if r.status == 'success')}` |",
                f"| **Failed Extractions** | `{stats.failed if stats else sum(1 for r in records if r.status != 'success')}` |",
                f"| **Success Rate** | `{stats.success_rate if stats else 100.0}%` |",
                f"| **Total Elapsed Time** | `{stats.elapsed_seconds if stats else 0.0}s` |",
                f"| **Throughput** | `{stats.requests_per_second if stats else 0.0} req/s` |",
                f"| **Total Data Processed** | `{stats.total_bytes_downloaded if stats else 0} bytes` |",
                "",
                "## 📋 Target Results Breakdown",
                "",
                "| URL / Source | Status | Parser | Duration | Extracted Details |",
                "| :--- | :--- | :--- | :--- | :--- |",
            ]

            for r in records:
                status_icon = "✅" if r.status == "success" else "❌"
                url_short = r.target_url if len(r.target_url) < 45 else r.target_url[:42] + "..."
                
                # Snippet of extracted detail
                if "title" in r.data:
                    snippet = f"Title: {r.data['title']}"
                elif "item_count" in r.data:
                    snippet = f"Items: {r.data['item_count']}"
                elif r.errors:
                    snippet = f"Error: {r.errors[0]}"
                else:
                    snippet = f"{len(r.data)} keys"

                snippet = snippet.replace("|", "/")
                lines.append(
                    f"| `{url_short}` | {status_icon} `{r.status}` | `{r.parser_type}` | `{r.duration_ms:.1f}ms` | {snippet} |"
                )

            lines.append("")
            lines.append("---")
            lines.append("*Generated by [AutoExtract Engine](https://github.com/kartavyapatel858-cloud)*")

            target_file.write_text("\n".join(lines), encoding="utf-8")
            return target_file

        except Exception as exc:
            raise ExportError(f"Failed to export Markdown to {target_file}: {exc}") from exc
